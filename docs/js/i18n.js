let currentLang = localStorage.getItem(STORAGE_KEY) || DEFAULT_LANG;
if (!translations[currentLang]) currentLang = DEFAULT_LANG;

export function getLang() {
  return currentLang;
}

export function setLang(lang) {
  if (!translations[lang]) return;
  currentLang = lang;
  localStorage.setItem(STORAGE_KEY, lang);
  document.documentElement.lang = lang;
  applyTranslations();
  document.dispatchEvent(new CustomEvent("langchange", { detail: { lang } }));
}

// Resolves a tournament status value (potentially manually-tweaked in the
// Firestore console with a typo, hyphen, casing, etc.) to a known i18n key
// for the admin status label.
const KNOWN_TOURNAMENT_STATUS = new Set(["open_submission", "running", "completed"]);
export function tournamentStatusLabel(rawStatus) {
  const normalized = String(rawStatus || "open_submission").replace(/-/g, "_").toLowerCase();
  const key = KNOWN_TOURNAMENT_STATUS.has(normalized) ? normalized : "open_submission";
  return t(`admin.status.${key}`);
}

export function t(key, params = {}) {
  let text = translations[currentLang][key];
  if (text === undefined) text = translations[DEFAULT_LANG][key];
  if (text === undefined) return key;
  for (const [k, v] of Object.entries(params)) {
    text = text.replace(new RegExp(`\\{${k}\\}`, "g"), v);
  }
  return text;
}

export function applyTranslations(root = document) {
  root.querySelectorAll("[data-i18n]").forEach((el) => {
    el.textContent = t(el.getAttribute("data-i18n"));
  });
  root.querySelectorAll("[data-i18n-html]").forEach((el) => {
    el.innerHTML = t(el.getAttribute("data-i18n-html"));
  });
  root.querySelectorAll("[data-i18n-placeholder]").forEach((el) => {
    el.placeholder = t(el.getAttribute("data-i18n-placeholder"));
  });
  root.querySelectorAll("[data-i18n-title]").forEach((el) => {
    el.title = t(el.getAttribute("data-i18n-title"));
  });
}

export function initLangToggle() {
  const buttons = document.querySelectorAll(".lang-toggle");
  if (!buttons.length) return;

  const updateAll = () => {
    buttons.forEach((btn) => {
      btn.textContent = currentLang === "en" ? "FR" : "EN";
      btn.title = currentLang === "en" ? "Passer en français" : "Switch to English";
    });
  };

  updateAll();
  buttons.forEach((btn) => {
    btn.addEventListener("click", () => {
      setLang(currentLang === "en" ? "fr" : "en");
      updateAll();
    });
  });
}

document.documentElement.lang = currentLang;
if (document.readyState === "loading") {
  document.addEventListener("DOMContentLoaded", () => {
    applyTranslations();
    initLangToggle();
  });
} else {
  applyTranslations();
  initLangToggle();
}
